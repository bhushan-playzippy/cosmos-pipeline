"""Finds a visual for each scene: Veo clip → Pexels video → NASA image → starfield."""
import os
import random
import re
import shutil
from pathlib import Path

import requests

from .util import ASSETS, DATA, read_json, write_json, log

USED = DATA / "used_media.json"
META = {}  # scene index → descriptive metadata of the asset just fetched (title, description, date, tags, page)
VISION_CACHE = DATA / "vision_cache.json"  # nasa_id -> True if the image has text/labels/people
# Basis for using each source commercially (recorded per scene for the rights check).
RIGHTS = {
    "nasa": "NASA media: generally not copyrighted, commercial use allowed; no NASA logo/endorsement implied "
            "(nasa.gov/nasa-brand-center/images-and-media)",
    "pexels": "Pexels License: free commercial use, no attribution required",
    "pixabay": "Pixabay Content License: free commercial use, no attribution required (pixabay.com/service/license)",
    "veo": "Generated by the channel owner with Google Veo (owner's own output)",
    "motion": "Original procedural motion graphic generated by this pipeline",
    "stars": "Generated by this pipeline (original)",
    "compare": "Original to-scale graphic generated by this pipeline",
    "commons": "Wikimedia Commons file marked Public domain or CC0 (no attribution required); file page recorded",
}
COMMONS_OK = re.compile(r"^(public domain|cc0|pd)", re.I)
# For history, portraits, maps and paintings are the point; only reject charts/logos/diagrams.
MAX_YEAR = 1990  # Commons "date taken" at or after this = a modern photo, not archive material
GENERIC = {"the", "and", "photo", "photograph", "picture", "image", "painting", "portrait", "old", "historic",
           "historical", "vintage", "file", "jpg", "jpeg", "png", "with", "from", "after", "before", "during",
           "where", "who", "that", "was", "were", "his", "her", "their", "this", "into", "over", "under", "how",
           "why", "what", "when", "which", "for", "not", "story", "real", "true", "famous", "first", "last"}
COMMONS_BAD = re.compile(r"logo|diagram|chart|graph|infographic|icon|coat of arms|flag of|signature|"
                         r"sculpture|statue|memorial|plaque|monument|bust of|reenact", re.I)
UA = {"User-Agent": "cosmic-scale-pipeline/1.0"}


def _download(url, dest, headers=None):
    with requests.get(url, headers={**UA, **(headers or {})}, stream=True, timeout=60) as r:
        r.raise_for_status()
        with open(dest, "wb") as f:
            for chunk in r.iter_content(1 << 16):
                f.write(chunk)
    return dest


def take_veo_clip(workdir, slug):
    """Uses assets/veo/<topic-slug>.mp4 if you made one in the Gemini app (see: python main.py veo-prompts)."""
    folder = ASSETS / "veo"
    clips = [p for p in folder.glob(f"{slug}.*") if p.suffix.lower() in {".mp4", ".mov", ".webm"}]
    if not clips:
        return None
    clip = clips[0]
    used_dir = folder / "used"
    used_dir.mkdir(exist_ok=True)
    dest = workdir / f"veo{clip.suffix.lower()}"
    shutil.copy(clip, dest)
    shutil.move(str(clip), used_dir / clip.name)
    log(f"hook uses your Veo clip: {clip.name}")
    return dest


def pexels_video(query, workdir, idx, used):
    key = os.environ.get("PEXELS_API_KEY")
    if not key:
        return None
    r = requests.get("https://api.pexels.com/videos/search",
                     params={"query": query, "orientation": "portrait", "per_page": 15, "size": "medium"},
                     headers={"Authorization": key, **UA}, timeout=30)
    r.raise_for_status()
    vids = [v for v in r.json().get("videos", []) if f"pexels:{v['id']}" not in used]
    if not vids:
        return None
    for v in random.sample(vids[:6], min(3, len(vids[:6]))):
        files = [f for f in v["video_files"] if f.get("height") and f.get("width") and f["height"] >= f["width"]
                 and f.get("file_type") == "video/mp4"]
        if not files:
            continue
        best = min(files, key=lambda f: abs(f["height"] - 1920))
        dest = _download(best["link"], workdir / f"scene_{idx:02d}.mp4")
        used.append(f"pexels:{v['id']}")
        if _too_dark(dest):
            continue
        META[idx] = {"title": query, "page": v.get("url"), "tags": (v.get("url") or "").rstrip("/").rsplit("/", 1)[-1]}
        return dest
    return None


def pixabay_video(query, workdir, idx, used):
    """Free stock video (PIXABAY_API_KEY, free at pixabay.com/api/docs). Landscape clips are cropped to 9:16 by render."""
    key = os.environ.get("PIXABAY_API_KEY")
    if not key:
        return None
    r = requests.get("https://pixabay.com/api/videos/", params={"key": key, "q": query[:100], "per_page": 20,
                                                                 "safesearch": "true"}, headers=UA, timeout=30)
    r.raise_for_status()
    hits = [h for h in r.json().get("hits", []) if f"pixabay:{h['id']}" not in used and h.get("duration", 0) >= 4]
    if not hits:
        return None
    for h in random.sample(hits[:6], min(3, len(hits[:6]))):
        size = next((h["videos"][s] for s in ("medium", "large", "small") if h["videos"].get(s, {}).get("url")
                     and h["videos"][s].get("size", 0) < 60_000_000), None)
        if not size:
            continue
        dest = _download(size["url"], workdir / f"scene_{idx:02d}.mp4")
        used.append(f"pixabay:{h['id']}")
        if _too_dark(dest):
            continue
        META[idx] = {"title": query, "page": h.get("pageURL"), "tags": h.get("tags", "")}
        return dest
    return None


def _too_dark(path):
    """A stock clip that fades in from black (or is a night shot) fails the render's "no black frames" gate, and a
    remake picked the same clip again: 9 quarantines 28 Oct-5 Nov. Rejected here, so the next candidate is tried."""
    from .qa import _blank_runs
    try:
        dark = bool(_blank_runs(path))
    except Exception:
        return False
    if dark:
        Path(path).unlink(missing_ok=True)
    return dark


# NASA results often include labelled diagrams, charts and posters; their text gets cropped mid-word on 9:16.
TEXTY = re.compile(r"infographic|diagram|chart|\bgraph\b|poster|logo|patch|annotated|label|illustration of|"
                   r"comparison|timeline|map of|\bplot\b|briefing|press conference|portrait", re.I)


def _has_text(item):
    """Also rejects third-party copyrighted items, which the NASA library sometimes hosts."""
    d = item["data"][0]
    if re.search(r"©|copyright|all rights reserved", d.get("description", "") + d.get("photographer", ""), re.I):
        return True
    return bool(TEXTY.search(" ".join([d.get("title", ""), d.get("description", "")[:300],
                                       " ".join(d.get("keywords", []))])))


def nasa_image(query, workdir, idx, used, cfg, check=None):
    """check(info) → grounding decision from the item's own metadata, judged before download (3 Nov: a NASA
    image of Earth and Mars played under Pluto narration and failed the grounding gate after the whole search)."""
    from .llm import image_has_text
    r = requests.get("https://images-api.nasa.gov/search",
                     params={"q": query, "media_type": "image"}, headers=UA, timeout=30)
    r.raise_for_status()
    all_items = r.json().get("collection", {}).get("items", [])
    exact_id = re.fullmatch(r"(?:art|iss|jsc|ksc|msfc|pia|arc|gsfc|nHQ|as|s)[-_A-Za-z0-9]+",
                            query.strip(), re.I) and any(c.isdigit() for c in query)
    if exact_id:
        all_items = [it for it in all_items
                     if it.get("data") and it["data"][0].get("nasa_id", "").lower() == query.strip().lower()]
    items = [it for it in all_items
             if it.get("links") and f"nasa:{it['data'][0]['nasa_id']}" not in used and not _has_text(it)]
    pool = items[:12]
    if not exact_id:
        random.shuffle(pool)
    if check:
        fits = [it for it in pool if check(_nasa_info(it)) != "MISMATCH"]
        if len(fits) < len(pool):
            log(f"scene {idx}: skipped {len(pool) - len(fits)} NASA image(s) that don't fit the narration")
        pool = fits
    for it in pool[:4]:  # metadata misses many labelled images, so also look at the picture itself
        thumb = it["links"][0]["href"]
        dest = workdir / f"scene_{idx:02d}.jpg"
        for size in ("~large.jpg", "~medium.jpg", "~thumb.jpg"):
            try:
                _download(thumb.replace("~thumb.jpg", size), dest)
                break
            except requests.HTTPError:
                continue
        else:
            continue
        nasa_id = it["data"][0]["nasa_id"]
        used.append(f"nasa:{nasa_id}")
        cache = read_json(VISION_CACHE, {})
        if nasa_id not in cache:  # each NASA image is only ever sent to Gemini once
            cache[nasa_id] = image_has_text(dest, cfg)
            write_json(VISION_CACHE, cache)
        if cache[nasa_id]:
            log(f"scene {idx}: skipped labelled NASA image ({it['data'][0].get('title', '')[:50]})")
            continue
        META[idx] = _nasa_info(it)
        return dest
    return None


def nasa_fits_scene(query, subject):
    """Is the scene's NASA query about the scene's subject at all? 3 Nov (Jupiter pressure): every cosmic scene
    carries a `nasa` query, so the everyday-comparison scenes (subject "basketball under pressure", "school bus
    compression", "Mariana Trench") got a Jupiter, Bahamas or cleanroom photo from NASA, which comes before stock
    in video.sources; the reviewer called 4 of 8 scenes MISMATCH and the verified video was quarantined twice.
    No shared distinctive word → skip NASA for this scene (stock footage of the `visual` comes next). A unique
    numeric NASA asset ID is already a precise selector; names_subject still checks the returned metadata."""
    q = (query or "").strip()
    if re.fullmatch(r"(?:art|iss|jsc|ksc|msfc|pia|arc|gsfc|nHQ|as|s)[-_A-Za-z0-9]+", q, re.I) and any(c.isdigit() for c in q):
        return True
    s = set(key_words(subject or ""))
    return not s or bool(s & set(key_words(q)))


def names_subject(subject, info):
    """A NASA candidate is used only when its own title/description/tags name the scene's subject (one
    distinctive word) in its title or tags. Before, metadata that merely didn't contradict the line (UNKNOWN) was accepted."""
    s = set(key_words(subject or ""))
    # title and tags only: 4 Nov an ISS-hardware photo and a JWST mirror passed under Moon lines because their
    # long descriptions mention the Moon in passing, and the reviewer quarantined the verified Moon Short twice
    hay = " ".join(str(info.get(k) or "") for k in ("title", "tags"))
    return not s or bool(s & set(key_words(hay)))


def _nasa_info(it):
    d = it["data"][0]
    return {"title": d.get("title", ""), "description": re.sub(r"<[^>]+>", " ", d.get("description", ""))[:400],
            "date": d.get("date_created", "")[:10], "tags": ", ".join(d.get("keywords", []))[:200],
            "page": f"https://images.nasa.gov/details/{d['nasa_id']}"}


def key_words(text):
    """Distinctive words of a query or topic: no years, no filler ("The 1942 Battle of Los Angeles where..." →
    battle, los, angeles)."""
    return [w for w in re.findall(r"[a-z]{3,}", text.lower()) if w not in GENERIC]


def commons_image(query, workdir, idx, used, subject=None, check=None):
    """Real historical photo/painting/map from Wikimedia Commons, public domain or CC0 only, at least 600 px.
    Long queries rarely match file names, so it retries with shorter forms ("Titanic leaving Southampton 1912"
    → "Titanic leaving Southampton" → "Titanic leaving"), but never down to fewer than two distinctive words
    ("Battle of Los Angeles" cut to "Battle of" found a Mexican-American War map). With `subject` (the story's
    main subject, e.g. "Wojtek bear"), every file must also be about that subject."""
    words = query.split()
    need = min(2, len(key_words(query)))
    for n in range(len(words), 0, -1):
        part = " ".join(words[:n])
        if len(key_words(part)) < need:
            break
        path, info = _commons_search(part, workdir, idx, used, subject, *([check] if check else []))
        if path:
            return path, info
    return None, None


# Wikimedia asks automated clients to identify themselves; a generic UA gets rate-limited (HTTP 429).
COMMONS_UA = {"User-Agent": "cosmos-pipeline/1.0 (YouTube Shorts research tool; https://www.youtube.com/@peakmomentsworld)"}


def _commons_get(url, **kw):
    import time
    time.sleep(0.4)  # polite pacing: bursts of requests get HTTP 429
    for attempt in range(4):
        r = requests.get(url, headers=COMMONS_UA, timeout=30, **kw)
        if r.status_code != 429:
            r.raise_for_status()
            return r
        time.sleep(2 * (attempt + 1))
    r.raise_for_status()


def commons_available(query, need=2, evidence=None):
    """Pre-check before any model call: does Commons have `need` usable images for this subject? (The query's own
    title match already ties each file to the subject; the scenes later add the writer's subject filter.)
    evidence: a list that receives one record per image actually found and downloaded (source, page, licence as
    Commons states it, download status, why it is relevant): the topic's visual_precheck. Public domain is
    claimed only where Commons' own LicenseShortName says so (COMMONS_OK); nothing else is accepted."""
    import tempfile
    found, used = 0, []
    with tempfile.TemporaryDirectory() as d:
        for _ in range(need):
            path, info = commons_image(query, Path(d), found, used)
            if not path:
                break
            found += 1
            if evidence is not None:
                evidence.append({
                    "source": "wikimedia_commons", "query": query, "title": (info or {}).get("title"),
                    "page": (info or {}).get("page"), "license": (info or {}).get("license"),
                    "license_evidence": "Commons file metadata (extmetadata.LicenseShortName)",
                    "date": (info or {}).get("date") or None, "downloaded": True, "bytes": path.stat().st_size,
                    "relevance": "file title shares the query's distinctive words",
                    "asset_id": used[-1] if used else None})
    return found >= need


def _about(page, ii, subject):
    """Does this file mention the story's subject (title, categories or description)? Needs two of the subject's
    distinctive words when it has two or more, so "Battle of Los Angeles" doesn't accept any battle."""
    stem = lambda ws: {w[:-1] if w.endswith("s") and len(w) > 3 else w for w in ws}  # funnel(s), bear(s)
    sw = stem(key_words(subject or ""))
    if not sw:
        return True
    meta = ii.get("extmetadata", {})
    hay = " ".join([page.get("title", ""), meta.get("Categories", {}).get("value", ""),
                    re.sub(r"<[^>]+>", " ", meta.get("ImageDescription", {}).get("value", ""))[:800],
                    meta.get("ObjectName", {}).get("value", "")]).lower()
    return len(sw & stem(re.findall(r"[a-z]{3,}", hay))) >= min(2, len(sw))


def _commons_search(query, workdir, idx, used, subject=None, check=None):
    r = _commons_get("https://commons.wikimedia.org/w/api.php", params={
        "action": "query", "format": "json", "generator": "search", "gsrnamespace": 6, "gsrlimit": 15,
        "gsrsearch": f"{query} filetype:bitmap", "prop": "imageinfo", "iiprop": "url|extmetadata|size",
        "iiurlwidth": 1600})
    pages = sorted(r.json().get("query", {}).get("pages", {}).values(), key=lambda p: p.get("index", 99))
    for p in pages:
        ii = (p.get("imageinfo") or [{}])[0]
        lic = ii.get("extmetadata", {}).get("LicenseShortName", {}).get("value", "")
        key = f"commons:{p['pageid']}"
        if not COMMONS_OK.match(lic) or key in used or min(ii.get("width", 0), ii.get("height", 0)) < 600:
            continue
        if COMMONS_BAD.search(p.get("title", "")):
            continue
        # the file must actually be about the query: share a real word with it (stops "LANSA" → a street photo)
        title_words = set(re.findall(r"[a-z]{3,}", p.get("title", "").lower()))
        meaningful = {w for w in re.findall(r"[a-z]{3,}", query.lower()) if w not in GENERIC}
        if len(title_words & meaningful) < min(2, len(meaningful)) or not _about(p, ii, subject):
            continue
        # archive images only: drop photos taken 1990 or later (modern meetings, statues, reenactments)
        meta = ii.get("extmetadata", {})
        taken = re.findall(r"\b(1[5-9]\d\d|20\d\d)\b", meta.get("DateTimeOriginal", {}).get("value", "")
                           or meta.get("DateTime", {}).get("value", "") if not meta.get("DateTimeOriginal") else
                           meta["DateTimeOriginal"].get("value", ""))
        # a "Public domain" archive scan often carries its digitisation date (e.g. 2013), so only modern CC0
        # uploads (people's own recent photos) are dropped by date
        if taken and min(map(int, taken)) >= MAX_YEAR:
            if lic.upper().startswith("CC0"):
                continue
            # "Public domain" + modern date is either an old photo's scan date or a modern US-government photo:
            # keep it only if its own description dates the picture before MAX_YEAR (e.g. "Italy, 1944")
            desc = re.sub(r"<[^>]+>", " ", meta.get("ImageDescription", {}).get("value", "") + " " + p.get("title", ""))
            if not any(int(y) < MAX_YEAR for y in re.findall(r"\b(1[5-9]\d\d)\b", desc)):
                continue
        info = {"license": lic, "page": ii.get("descriptionurl"), "title": p.get("title", ""),
                "description": re.sub(r"\s+", " ", re.sub(r"<[^>]+>", " ", meta.get("ImageDescription", {})
                                                         .get("value", "")))[:400],
                "date": re.sub(r"<[^>]+>", " ", meta.get("DateTimeOriginal", {}).get("value", ""))[:60],
                "categories": meta.get("Categories", {}).get("value", "")[:300]}
        if check and check(info) == "MISMATCH":  # grounding: e.g. a 2003 artifact photo for "the sub sank"
            log(f"scene {idx}: skipped {p.get('title', '')[:60]} (doesn't fit the narration)")
            continue
        dest = workdir / f"scene_{idx:02d}.jpg"
        raw = workdir / f"scene_{idx:02d}.raw"
        raw.write_bytes(_commons_get(ii.get("thumburl") or ii["url"]).content)
        try:  # normalise: some archive files are CMYK/16-bit/palette TIFF-in-JPEG that FFmpeg can't decode
            from PIL import Image
            with Image.open(raw) as im:
                im.convert("RGB").save(dest, "JPEG", quality=92)
        except Exception:
            continue
        finally:
            raw.unlink(missing_ok=True)
        used.append(key)
        return dest, info
    return None, None


def starfield(workdir, idx, w=1080, h=1920, slug=""):
    """Generated fallback: deep-space starfield with a soft nebula glow."""
    from PIL import Image, ImageDraw, ImageFilter
    rnd = random.Random(f"{slug}-{idx}")  # per video + scene, so videos don't share identical backgrounds
    W, H = w * 2, h * 2
    img = Image.new("RGB", (W, H), (4, 5, 14))
    glow = Image.new("RGB", (W, H), (0, 0, 0))
    gd = ImageDraw.Draw(glow)
    palette = [(90, 40, 160), (20, 90, 170), (170, 50, 110), (30, 140, 150)]
    for _ in range(5):
        cx, cy, r = rnd.randint(0, W), rnd.randint(0, H), rnd.randint(W // 5, W // 2)
        gd.ellipse([cx - r, cy - r, cx + r, cy + r], fill=rnd.choice(palette))
    glow = glow.filter(ImageFilter.GaussianBlur(W // 8))
    img = Image.blend(img, glow, 0.55)
    d = ImageDraw.Draw(img)
    for _ in range(2600):
        x, y = rnd.randint(0, W), rnd.randint(0, H)
        s = rnd.choice([1, 1, 1, 2, 2, 3])
        b = rnd.randint(150, 255)
        d.ellipse([x, y, x + s, y + s], fill=(b, b, min(255, b + 20)))
    dest = workdir / f"scene_{idx:02d}.png"
    img.save(dest)
    return dest


def gather(timeline, cfg, workdir, slug="", only=None):
    """Picks each scene's asset (profile's video.sources order) and records its provenance and metadata.
    Grounding (2 Nov): an archive image whose metadata contradicts its line (an artifact or later photo under
    event narration, the wrong period or body) is skipped while searching; an image is used on at most
    visual.max_image_uses scenes. asset_id is the asset actually shown: before 2 Nov a reused image recorded the
    id of whatever was downloaded last (Hunley scene 3 showed the painting but listed the pocket watch).
    only: scene indices to (re)fetch; the others keep their asset (3 Nov, stage recovery: a grounding MISMATCH
    replaces that scene's picture instead of failing a verified video). The rejected asset is already in
    used_media, so the new search can't return it."""
    from . import grounding
    sources = cfg["video"]["sources"]
    used = read_json(USED, [])
    uses = {}
    cap = cfg.get("visual", {}).get("max_image_uses", 4)
    story = cfg.get("writer", {}).get("template") == "story"
    years = grounding._years(" ".join(t.get("text", "") for t in timeline))
    ai_realistic = False
    banned = set()  # ids a remake must not draw again (orchestrator._avoid_rejected); not kept in used_media
    for t in timeline if only is not None else []:  # reuse counts of the scenes being kept
        if t.get("reused_from"):
            uses[t["reused_from"]] = uses.get(t["reused_from"], 1) + 1
    for i, sc in enumerate(timeline):
        if only is not None and i not in only:
            continue
        for k in ("reused_from", "commons_file"):  # a replaced scene keeps nothing of the asset it loses
            if k == "commons_file" and sc.get("local_image"):
                continue  # preserve the licence metadata paired with a manually pinned image
            sc.pop(k, None)
        path, kind, asset_id = None, None, None
        META.pop(i, None)
        sc.pop("asset", None)
        subject = grounding.subject_of(sc)
        avoid = sc.get("avoid") or {}
        new_bans = [a for a in avoid.get("assets", []) if a and a not in used]
        used.extend(new_bans)
        banned.update(new_bans)
        order = (["motion"] if sc.get("motion") else []) + (["compare"] if sc.get("compare") else []) + list(sources)
        if avoid:  # a scene the reviewer rejected: skip that kind of source, and before the starfield try a real
            # image of the video's main subject (the ISS under "bigger than a six-bedroom house")
            order = [x for x in order if x not in avoid.get("sources", [])]
            at = order.index("stars") if "stars" in order else len(order)
            order.insert(at, "subject")
        fits = lambda info, sc=sc, subject=subject, src="commons": grounding.judge(
            sc.get("text", ""), subject, {"source": src, "id": "x", "license": "x", "page": "x", **info}, years,
            story)[0]
        for src in order:
            n_used = len(used)
            try:
                if src == "motion":
                    from . import motiongfx
                    path, kind = motiongfx.render(sc["motion"], workdir / f"motion_{i:02d}.mp4"), "video"
                elif src == "compare":
                    from . import scalegfx
                    if not scalegfx.valid(sc["compare"]):
                        continue
                    path, kind = scalegfx.render(sc["compare"], workdir / f"compare_{i:02d}.png"), "image"
                elif src == "veo" and i == 0:
                    path, kind = take_veo_clip(workdir, slug), "video"
                    ai_realistic = ai_realistic or bool(path)
                elif src == "pixabay":
                    path, kind = pixabay_video(sc.get("visual", "space"), workdir, i, used), "video"
                elif src == "pexels":
                    path, kind = pexels_video(sc.get("visual", "space"), workdir, i, used), "video"
                elif src == "commons":
                    path, info = None, None
                    # A manually reviewed Commons asset can be pinned without weakening provenance or grounding.
                    # The same metadata judge applies; if it fails, the normal Commons search still runs.
                    local = sc.get("local_image")
                    supplied = sc.get("commons_file")
                    if local and supplied and Path(local).is_file() and fits(supplied) != "MISMATCH":
                        path = workdir / f"scene_{i:02d}.jpg"
                        shutil.copy(local, path)
                        info = supplied
                        asset_id = sc.get("asset_id") or supplied.get("page")
                    # every image must be about the story's subject; old scripts without one use the topic's words
                    subject_q = sc.get("commons_subject") or " ".join(key_words(slug.replace("-", " "))[:3])
                    queries = [sc.get("commons") or sc.get("visual", "history"), subject_q]
                    for q in [q for q in queries if q] if not path else []:
                        try:  # a network error on one query must not skip the reuse fallback below
                            path, info = commons_image(q, workdir, i, used, subject=subject_q, check=fits)
                        except Exception as e:
                            log(f"scene {i}: commons '{q}' failed ({str(e)[:80]})")
                        if path:
                            break
                    if not path:  # still nothing: reuse an earlier on-subject image of this story, if it fits
                        # this line too and hasn't hit visual.max_image_uses (Hunley: 4 images for 9 scenes)
                        prev = [t for t in timeline[:i] if (t.get("rights") or {}).get("source") == "commons"
                                and not t.get("reused_from") and uses.get(t["media"], 1) < cap
                                and t.get("commons_file") and fits(t["commons_file"]) != "MISMATCH"]
                        if prev:
                            src_prev = min(prev, key=lambda t: uses.get(t["media"], 1))
                            uses[src_prev["media"]] = uses.get(src_prev["media"], 1) + 1
                            path = workdir / f"scene_{i:02d}.jpg"
                            shutil.copy(src_prev["media"], path)
                            info = src_prev.get("commons_file")
                            sc["reused_from"] = src_prev["media"]
                            asset_id = (src_prev.get("rights") or {}).get("asset_id")
                    kind = "image"
                    if info:
                        sc["commons_file"] = info
                elif src == "nasa":
                    q = sc.get("nasa") or sc.get("visual", "galaxy")
                    if not nasa_fits_scene(q, subject):
                        continue  # the writer's own space query isn't about this scene ("Jupiter" under a basketball)
                    path, kind = nasa_image(q, workdir, i, used, cfg, check=lambda info, f=fits, s=subject: f(
                        info, src="nasa") if names_subject(s, info) else "MISMATCH"), "image"
                elif src == "subject":
                    main = sc.get("commons_subject") or " ".join(key_words(slug.replace("-", " "))[:3])
                    if "nasa" not in sources or not main:
                        continue
                    path, kind = nasa_image(main, workdir, i, used, cfg, check=lambda info, f=fits, s=main: f(
                        info, src="nasa") if names_subject(s, info) else "MISMATCH"), "image"
                    if path:
                        src = "nasa"
                elif src == "stars":
                    path, kind = starfield(workdir, i, slug=slug), "image"
            except Exception as e:
                log(f"scene {i}: {src} failed ({str(e)[:100]})")
                path = None
            if path:
                if not asset_id and len(used) > n_used:
                    asset_id = used[-1]  # what this scene itself downloaded
                break
        sc["media"], sc["media_kind"] = str(path), kind
        sc["rights"] = {"source": src, "license": RIGHTS.get(src, "unknown"),
                        "asset_id": asset_id if src in ("nasa", "pexels", "pixabay", "commons") else None}
        if src == "motion" and sc.get("motion", {}).get("nasa"):
            nasa_id = sc["motion"]["nasa"]
            sc["rights"].update(asset_id=f"nasa:{nasa_id}", page=f"https://images.nasa.gov/details/{nasa_id}",
                                texture_license=RIGHTS["nasa"])
        if src == "commons" and sc.get("commons_file"):
            sc["rights"].update(file_license=sc["commons_file"]["license"], page=sc["commons_file"]["page"])
        if i in META:
            sc["asset"] = META.pop(i)
            if sc["asset"].get("page") and src in ("nasa", "pexels", "pixabay"):
                sc["rights"]["page"] = sc["asset"]["page"]
        log(f"scene {i}: {Path(path).name} ({kind})")
    write_json(USED, [u for u in used if u not in banned][-3000:])
    return timeline, ai_realistic

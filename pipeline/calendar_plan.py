"""Editorial planning agent: a rolling 30-day calendar (the profile's slots) built from the scored topic backlog.

The calendar is a plan, not a commitment: production (orchestrator.produce) still picks the best unused topic
for each slot's role at make time, so the plan adapts as analytics change the backlog ordering.
Paths follow the active channel (jobs.HISTORY / analytics.REPORTS): a shared file let one channel's plan
overwrite the other's.
"""
import datetime as dt

from . import analytics, ideas, jobs
from .util import read_json, write_json, log


def calendar_path():
    return jobs.HISTORY.parent / "calendar.json"


def md_path():
    return analytics.REPORTS / "CONTENT_CALENDAR.md"


def build(cfg, days=30, fill=False):
    plan = cfg.get("planning", {})
    slots_needed = days * cfg["schedule"].get("videos_per_day", 3)
    backlog = read_json(ideas.BACKLOG, [])
    while fill and len(backlog) < slots_needed:
        before = len(backlog)
        backlog = ideas.refill_backlog(cfg)
        if len(backlog) == before:
            break
    pool = list(backlog)
    all_jobs = jobs.load()
    pillars = plan.get("pillars", [])
    entries, last_pillar = [], None
    start = jobs.now().date()
    for d in range(days):
        day = start + dt.timedelta(days=d)
        for st in jobs._slot_times(cfg):
            slot = dt.datetime.combine(day, st, tzinfo=jobs.TZ)
            if slot < jobs.now():
                continue
            role = jobs.role_for(cfg, slot)
            existing = next((j for j in all_jobs if jobs.when(j) and abs(jobs.when(j) - slot) < dt.timedelta(hours=2)), None)
            if existing:
                entries.append({"slot": slot.isoformat(), "role": existing.get("role") or role,
                                "topic": existing["topic"], "status": existing["status"],
                                "youtube_id": existing.get("youtube_id")})
                continue
            pick = (next((t for t in pool if t.get("role") == role and t.get("pillar") != last_pillar), None)
                    or next((t for t in pool if t.get("role") == role), None)
                    or (pool[0] if pool else None))
            if pick:
                pool.remove(pick)
                last_pillar = pick.get("pillar")
                entries.append({"slot": slot.isoformat(), "role": role, "topic": pick["topic"],
                                "pillar": pick.get("pillar"), "series": pick.get("series"),
                                "benefit": pick.get("viewer_benefit"), "score": pick.get("score"),
                                "status": "planned"})
            else:
                p = pillars[len(entries) % len(pillars)] if pillars else "any"
                entries.append({"slot": slot.isoformat(), "role": role, "topic": None, "pillar": p,
                                "status": "open (topic chosen at production time)"})
    write_json(calendar_path(), entries)
    _write_md(entries)
    log(f"calendar: {len(entries)} slots, {sum(1 for e in entries if e.get('topic'))} with topics → {calendar_path()}")
    return entries


def _write_md(entries):
    lines = ["# 30-day content calendar", "",
             "Generated by `python main.py calendar`. Slots are IST. A plan, not a promise: production re-picks the",
             "best unused topic for each slot's role at make time. Scores are model estimates (no search-volume data).", "",
             "| Slot (IST) | Role | Pillar / series | Topic | Score | Status |", "|---|---|---|---|---|---|"]
    for e in entries:
        s = dt.datetime.fromisoformat(e["slot"])
        ps = " / ".join(x for x in (e.get("pillar"), e.get("series")) if x) or "-"
        lines.append(f"| {s:%a %d %b %H:%M} | {e['role']} | {ps} | {e.get('topic') or '—'} | "
                     f"{e.get('score') or ''} | {e['status']} |")
    md_path().parent.mkdir(parents=True, exist_ok=True)
    md_path().write_text("\n".join(lines) + "\n", encoding="utf-8")

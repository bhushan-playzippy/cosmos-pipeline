GOOD = {"source": "stars", "license": "Generated by this pipeline (original)"}


def _nasa(title):
    return {"source": "nasa", "license": "NASA media (no copyright)", "asset_id": "nasa:x1",
            "page": "https://images.nasa.gov/details/x1"}, {"title": title, "description": "", "tags": "", "date": ""}


def _gather(calls, bad_scene=2, fixed_after=1):
    """Fake visuals.gather: scene `bad_scene` first gets a NASA picture of Earth and Mars (MISMATCH under Pluto
    narration); a re-gather of only that scene gets a starfield after `fixed_after` replacement round(s)."""
    def gather(timeline, cfg, work, slug, only=None):
        calls.append(None if only is None else sorted(only))
        rounds = sum(1 for c in calls if c is not None)
        for i, t in enumerate(timeline):
            if only is not None and i not in only:
                continue
            if i == bad_scene and rounds < fixed_after:
                t["rights"], t["asset"] = _nasa("Earth and Mars from orbit")
            else:
                t["rights"], t["asset"] = dict(GOOD), {}
        return timeline, False
    return gather



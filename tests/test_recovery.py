# ---------------------------------------------------------------- Task 1: immutable verified record

def test_verified_record_is_written_once_per_fingerprint(cfg, fixed_now, tmp_path):
    folder = orchestrator.OUTPUT / "f1"
    folder.mkdir(parents=True)
    s = make_script("Rec")
    s = {**s, "claims": [{"claim": "c", "status": "VERIFIED"}]}
    s["claims_for"] = verify.fingerprint(s)
    p = orchestrator.persist_verified(folder, s)
    assert p.name == "verified.json" and orchestrator.persist_verified(folder, s) == p  # idempotent
    s2 = json.loads(json.dumps(s))
    s2["scenes"][0]["text"] = "Changed and verified again."
    s2["claims_for"] = verify.fingerprint(s2)
    p2 = orchestrator.persist_verified(folder, s2)
    assert p2 != p and read_json(p, {})["fingerprint"] == s["claims_for"]  # the first version is untouched
    unverified = {**s2, "claims_for": "v2:stale"}
    assert orchestrator.persist_verified(folder, unverified) is None


def test_retention_never_prunes_verified_records(cfg, fixed_now):
    d = orchestrator.OUTPUT / "old"
    d.mkdir(parents=True)
    for n in ("video.mp4", "verified.json", "script.json"):
        (d / n).write_text("{}")
    jobs.upsert({"folder": "old", "topic": "old", "status": "failed", "created": "2026-01-01T00:00:00"})
    health.prune(cfg, dry=False)
    assert sorted(p.name for p in d.iterdir()) == ["script.json", "verified.json"]


# ---------------------------------------------------------------- Task 5: a deferred draft doesn't block the run

def test_a_draft_that_defers_again_gives_the_slot_to_a_fresh_topic(cfg, monkeypatch, fixed_now):
    _fake_production(monkeypatch)
    today = jobs.now().date().isoformat()
    write_json(ideas.BACKLOG, [{"topic": "Old draft", "score": 30, "draft": make_script("Old draft"),
                                "draft_saved": today}, {"topic": "Fresh one", "score": 20}]
               + [{"topic": f"f{i}", "score": 1} for i in range(9)])

    def check(s, c):
        if s["topic"] == "Old draft":
            raise llm.Deferred("Gemini skipped for 'verify'", "overload")
        return {**s, "claims": [{"claim": "c", "decision": "pass"}], "claims_for": verify.fingerprint(s)}
    monkeypatch.setattr("pipeline.verify.check", check)
    job = orchestrator.make_video(cfg)
    assert job["status"] == "ready" and job["topic"] == "Fresh one"
    kept = [t for t in read_json(ideas.BACKLOG, []) if t["topic"] == "Old draft"]
    assert kept and kept[0]["draft"]  # still saved for a later run



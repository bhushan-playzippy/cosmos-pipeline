def test_research_notes_reach_the_writer_and_the_timeline_is_kept(cfg, monkeypatch):
    monkeypatch.setattr("pipeline.evidence.reference", lambda q, pages=2: DOCS)
    prompts = []
    scenes = [{"text": f"In 1915 the Endurance was trapped and crushed, and all 28 men lived, part {i} of it."}
              for i in range(8)]
    out = {"topic": "Shackleton", "timeline": [{"when": "1915", "event": "trapped", "notes": [2]}], "scenes": scenes,
           "youtube": {"title": "t", "description": "d"}}
    monkeypatch.setattr(storygen, "ask_json", lambda p, c, **k: prompts.append(p) or json.loads(json.dumps(out)))
    monkeypatch.setattr(storygen, "polish", lambda s, c: s)
    s = storygen.write_script({"topic": "The 1915 Ernest Shackleton Endurance expedition trapped in pack ice"}, cfg)
    assert "RESEARCH NOTES" in prompts[0] and "Weddell Sea" in prompts[0] and '"timeline"' in prompts[0]
    assert s["research"]["timeline"] and s["research"]["sources"][0]["url"].startswith("https://en.wikipedia.org")
    assert "RESEARCH NOTES" in prompts[1]  # the fact-check has the same notes
    assert "Endurance (1912 ship)" not in verify._prompt(s, cfg)  # the independent verifier stays blind



def test_a_scene_that_never_fits_fails_visuals_but_keeps_the_verified_work(cfg, monkeypatch, pluto):
    calls = []
    monkeypatch.setattr(visuals, "gather", _gather(calls, fixed_after=99))
    job = orchestrator.make_video(cfg)
    assert job["status"] == "failed" and job["stage_failed"] == "visuals" and job.get("resumable")
    assert calls == [None, [2], [2]]  # visual.scene_retries (2) replacement rounds, then it stops
    d = orchestrator.OUTPUT / job["folder"]
    rec = read_json(d / "verified.json", {})
    assert rec["fingerprint"].startswith("v2:") and rec["claims"] and rec["scene_plan"]
    assert not os.stat(d / "verified.json").st_mode & stat.S_IWUSR  # read-only
    kept = read_json(d / "script.json", {})
    assert kept["pipeline_state"]["failed_stage"] == "visuals" and kept["claims_for"] == rec["fingerprint"]
    back = read_json(ideas.BACKLOG, [])[0]
    assert back["topic"] == "Pluto" and back["draft_stage"] == "visuals" and back["draft"]["claims_for"]
    assert "Pluto" not in ideas.done_topics()  # a resumable failure doesn't burn the topic



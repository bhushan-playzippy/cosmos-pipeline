class FakeModels:
    def __init__(self, behaviour):
        self.behaviour, self.calls = behaviour, []

    def generate_content(self, model, contents, config):
        self.calls.append(model)
        r = self.behaviour(model)
        if isinstance(r, Exception):
            raise r
        return type("R", (), {"text": r})()



def test_watchdog_uses_the_wall_clock(monkeypatch):
    import threading
    import time
    import main
    exits, start = [], time.time()
    monkeypatch.setattr("os._exit", lambda code: exits.append(code))
    monkeypatch.setattr("faulthandler.dump_traceback", lambda **k: None)
    monkeypatch.setattr("time.sleep", lambda s: None)
    main.watchdog(60)                                     # deadline from the real wall clock
    monkeypatch.setattr("time.time", lambda: start + 10_000)  # hours later, e.g. after the Mac slept
    for t in threading.enumerate():
        if t.name == "watchdog":
            t.join(2)
    assert exits == [3]


class FakeGroq:
    """requests.post stand-in for an OpenAI-compatible provider; behaviour(model, body) → (status, text|dict)."""
    def __init__(self, behaviour):
        self.behaviour, self.calls = behaviour, []

    def __call__(self, url, json=None, headers=None, timeout=None):
        self.calls.append((json["model"], dict(json), headers))
        status, payload = self.behaviour(json["model"], json)
        body = payload if isinstance(payload, dict) else {"choices": [{"message": {"content": payload}}]}
        return type("R", (), {"status_code": status, "text": str(payload), "json": lambda self: body})()



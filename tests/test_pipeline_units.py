def test_profit_and_debt_cash_are_different_numbers(cfg):
    cfg["finance"].update(tax_rate=0.3, reserve=500, other_obligations=0)
    L = [{"kind": "revenue", "status": "earned", "amount": "3000"},      # earned, not paid yet
         {"kind": "revenue", "status": "received", "amount": "2000"},
         {"kind": "expense", "status": "paid", "amount": "400"},
         {"kind": "expense", "status": "owed", "amount": "100"},
         {"kind": "refund", "status": "paid", "amount": "0"}]
    c = finance.compute(cfg, L)
    assert c["operating_profit"] == 4500                     # 5000 recognised − 500 expenses
    assert c["tax_provision"] == pytest.approx(1350)
    # 2000 received − 400 paid − 100 owed − 500 reserve − 1350 tax → negative → 0
    assert c["debt_repayment_cash"] == 0



def _scripted_make_video(monkeypatch, outcomes):
    """make_video stand-in: each call returns the next outcome (status, stage_failed, reason) as a recorded job."""
    calls = []

    def fake(cfg, slot=None, **kw):
        status, stage, reason = outcomes[len(calls)]
        calls.append(slot)
        return jobs.upsert({"folder": f"f{len(calls)}", "topic": "t", "status": status, "stage_failed": stage,
                            "reason": reason, "slot": slot.isoformat() if status != "failed" else None})
    monkeypatch.setattr(orchestrator, "make_video", fake)
    return calls


